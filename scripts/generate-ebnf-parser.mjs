import { readFile, writeFile } from 'node:fs/promises';
import { createEbnfLexer } from '../src/client/classes/EbnfLexer.js';
import { createEbnfParser } from '../src/client/classes/EbnfParser.js';
import { ebnfMetaActionRules, ebnfMetaActions } from '../src/client/classes/EbnfMeta.js';

const grammarPath = new URL('../src/client/grammars/ebnf.ebnf', import.meta.url);
const outputPath = new URL('../src/client/classes/Ebnf.generated.js', import.meta.url);
const grammarSource = await readFile(grammarPath, 'utf8');

function literal (character) {
    const quote = character === '"' ? "'" : '"';
    return `${quote}${character}${quote}`;
}

function ranges (characters) {
    const values = [...characters].sort((a, b) => a - b);
    const intervals = [];
    for (const value of values) {
        const last = intervals.at(-1);
        if (last && last[1] + 1 === value) last[1] = value;
        else intervals.push([value, value]);
    }
    return intervals.map(([first, last]) => first === last
        ? literal(String.fromCharCode(first))
        : `${literal(String.fromCharCode(first))}..${literal(String.fromCharCode(last))}`).join(' | ');
}

function codeUnits (predicate, excluded = []) {
    const omit = new Set(excluded);
    const values = [];
    for (let code = 0; code <= 0xffff; code++) {
        if (!omit.has(code) && predicate(String.fromCharCode(code))) values.push(code);
    }
    return values;
}

const doubleQuoteCharacters = ranges(codeUnits(char => true, [0x22, 0x5c, 0x03b5]));
const singleQuoteCharacters = ranges(codeUnits(char => true, [0x27, 0x5c, 0x03b5]));
const whitespaceCharacters = ranges(codeUnits(char => /\s/.test(char), [0x03b5]));
const lexerGrammar = String.raw`
    letter = "A".."Z" | "a".."z" | "_";
    digit = "0".."9";
    nameStart = letter;
    nameCharacter = letter | digit;
    NAME = nameStart, { nameCharacter };
    escaped = "\\", ("n" | "r" | "t" | "f" | "v" | "\\" | "\"" | "'");
    doubleCharacter = ${doubleQuoteCharacters};
    singleCharacter = ${singleQuoteCharacters};
    doubleQuoted = "\"", { doubleCharacter | escaped }, "\"";
    singleQuoted = "'", { singleCharacter | escaped }, "'";
    LITERAL = doubleQuoted | singleQuoted;
    DOTDOT = "..";
    EQUAL = "=";
    SEMICOLON = ";";
    COMMA = ",";
    BAR = "|";
    LPAREN = "(";
    RPAREN = ")";
    LBRACKET = "[";
    RBRACKET = "]";
    LBRACE = "{";
    RBRACE = "}";
    SPACE = ${whitespaceCharacters};
`;

const outputTokenTypes = {
    NAME: 'name',
    LITERAL: 'literal',
    DOTDOT: '..',
    EQUAL: '=',
    SEMICOLON: ';',
    COMMA: ',',
    BAR: '|',
    LPAREN: '(',
    RPAREN: ')',
    LBRACKET: '[',
    RBRACKET: ']',
    LBRACE: '{',
    RBRACE: '}',
    SPACE: 'space'
};
const tokenActions = Object.fromEntries(Object.entries(outputTokenTypes).map(([name, tokenType]) => [
    name,
    lexer => ({ tokenType, content: lexer.yytext })
]));
const lexer = createEbnfLexer(lexerGrammar, {
    tokens: Object.keys(outputTokenTypes),
    actions: tokenActions
});
const initialState = lexer.INITIAL.start[0];
function transition (state, character) {
    const edge = lexer.INITIAL.table.find(jump =>
        jump.from === state && jump._ft_ <= character && jump._tt_ >= character
    );
    if (!edge) throw new Error(`Missing lexer transition for ${JSON.stringify(character)}`);
    return edge.to;
}

for (const quote of ['"', "'"]) {
    const quoteState = transition(initialState, quote);
    const bodyState = transition(quoteState, 'x');
    lexer.INITIAL.table.push(
        { from: quoteState, to: bodyState, _ft_: 'ε', _tt_: 'ε' },
        { from: bodyState, to: bodyState, _ft_: 'ε', _tt_: 'ε' }
    );
}

const parser = createEbnfParser(grammarSource, {
    start: 'document',
    tokens: ['name', 'literal'],
    actions: ebnfMetaActionRules,
    ignoreTokens: ['space']
});

const parserActionNames = new Map(
    Object.entries(ebnfMetaActions)
        .filter(([name]) => name !== 'root')
        .map(([name, action]) => [action, name])
);
const generatedStates = parser.states.map(state => {
    const action = parserActionNames.get(state.action) ||
        (state.create.startsWith('__ebnf_') ? 'root' : undefined);
    if (!action) throw new Error(`Missing generated parser action for ${state.create}`);
    return { create: state.create, base: state.base, action };
});

const lexerEndMap = Object.entries(lexer.INITIAL.endMap).map(([state, entry]) => {
    const action = Object.entries(tokenActions).find(([, candidate]) => candidate === entry.parseFunction);
    if (!action) throw new Error(`Missing generated lexer action for state ${state}`);
    return {
        state,
        tokenType: outputTokenTypes[action[0]]
    };
});
const generatedSource = `// Generated by npm run generate:ebnf. Do not edit.
import { ebnfMetaActions } from './EbnfMeta.js';

const endMap = {
${lexerEndMap.map(({ state, tokenType }) =>
        `    ${JSON.stringify(state)}: { parseFunction: lexer => ({ tokenType: ${JSON.stringify(tokenType)}, content: lexer.yytext }) }`
    ).join(',\n')}
};

export const ebnfLexerTable = {
    INITIAL: {
        table: ${JSON.stringify(lexer.INITIAL.table)},
        endMap
    }
};

export const ebnfParserConfig = {
    table: ${JSON.stringify(parser.table)},
    states: ${JSON.stringify(generatedStates)}.map(({ create, base, action }) => ({
        create,
        base,
        action: ebnfMetaActions[action]
    })),
    ignoreTokens: ${JSON.stringify(parser.ignoreTokens)}
};
`;
await writeFile(outputPath, generatedSource);
